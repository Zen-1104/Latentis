@dataclass
class MeasurementRecord:
    """A single row in the long-format measurements table (DATASET_SPEC.md § 5.1)."""

    component_id: str
    lot_id: str
    component_type: str
    parameter: str
    elapsed_hours: int
    measurement_value: float
    measurement_unit: str
    status: str = MeasurementStatus.OK.value
    temperature_c: float = 125.0
    voltage_v: float = 3.3
    read_timestamp: str = "2026-09-01T08:00:00Z"
    absolute_limit_low: float | None = None
    absolute_limit_high: float | None = None
    board_id: str = "BRD-01"
    socket_id: str = "SOCK-01"
    thermal_zone: str = "ZONE-1"
    tester_id: str = "TESTER-01"
    operator_id: str = "OP-01"
    data_provenance: str = "SYNTHETIC"  # Fixed constant per DR-09 / INV-3
    ingest_id: str = "ING-2026-001"
    is_duplicate: bool = False

    def to_dict(self) -> dict[str, Any]:
        """Convert to dictionary for serialization."""
        d = asdict(self)
        # Internal flag not part of emitted schema
        d.pop("is_duplicate", None)
        return d

    @property
    def is_censored(self) -> bool:
        """True if reading is censored (BELOW_LOD or OVERRANGE)."""
        return self.status in (MeasurementStatus.BELOW_LOD.value, MeasurementStatus.OVERRANGE.value)

    @property
    def is_below_lod(self) -> bool:
        """True if reading is below limit of detection."""
        return self.status == MeasurementStatus.BELOW_LOD.value

    @property
    def is_overrange(self) -> bool:
        """True if reading exceeded instrument measurement range."""
        return self.status == MeasurementStatus.OVERRANGE.value


