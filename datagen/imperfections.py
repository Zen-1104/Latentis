@dataclass
class ImperfectionResult:
    """Summary of injected realistic imperfections and observed rates."""

    total_initial_records: int
    total_emitted_records: int
    missing_count: int
    missing_rate_observed: float
    below_lod_count: int
    below_lod_rate_observed: float
    overrange_count: int
    overrange_rate_observed: float
    duplicate_count: int
    duplicate_rate_observed: float
    timestamp_jitter_count: int
    timestamp_jitter_rate_observed: float
    unit_inconsistent_lot_count: int
    msa_noise_applied: bool

    def to_dict(self) -> dict[str, Any]:
        """Convert to audit dictionary."""
        return asdict(self)


class ImperfectionInjector:
    """Master orchestrator for injecting realistic data imperfections (T-204).

    Applies the full imperfection stack per DATASET_SPEC § 8:
      - MSA noise (Gage R&R repeatability & reproducibility)
      - BELOW_LOD & OVERRANGE censoring
      - Missing read-point rows
      - Duplicate rows
      - Timestamp jitter
      - Unit inconsistencies
    """

    def __init__(
        self,
        config: DatagenConfig | None = None,
        limits: dict[str, ParameterLimitConfig] | None = None,
        rng: np.random.Generator | None = None,
    ) -> None:
        """Initialize the imperfection injector.

        Args:
            config: Datagen configuration containing imperfection rates.
            limits: Parameter screening limits.
            rng: Random generator.
        """
        self.config = config
        self.limits = limits if limits is not None else default_parameter_limits()
        self.rng = rng if rng is not None else np.random.default_rng(20260930)

        # Extract rates from config or defaults
        if self.config is not None:
            imp = self.config.imperfections
            self.missing_rate = float(imp.missing_rate.value)
            self.below_lod_rate = float(imp.below_lod_rate.value)
            self.overrange_rate = float(imp.overrange_rate.value)
            self.duplicate_rate = float(imp.duplicate_rate.value)
            self.timestamp_jitter_rate = float(imp.timestamp_jitter_rate.value)
        else:
            self.missing_rate = 0.015
            self.below_lod_rate = 0.005
            self.overrange_rate = 0.002
            self.duplicate_rate = 0.003
            self.timestamp_jitter_rate = 0.010

    def apply(
        self,
        records: list[MeasurementRecord],
        unit_mismatch_lots: set[str] | list[str] | None = None,
        apply_msa: bool = True,
        escape_component_ids: set[str] | list[str] | None = None,
    ) -> tuple[list[MeasurementRecord], ImperfectionResult]:
        """Apply all configured imperfections to a list of measurement records.

        Args:
            records: Initial measurement records.
            unit_mismatch_lots: Specific lots to inject unit mismatches into.
            apply_msa: If True, inject MSA repeatability & reproducibility noise.
            escape_component_ids: Specific component IDs belonging to the Escape Set (S1, S2)
                that must never violate absolute screening limits (TEST-GEN-004 / DR-04).

        Returns:
            tuple of (final_emitted_records, imperfection_audit_result).
        """
        initial_count = len(records)
        if initial_count == 0:
            return [], ImperfectionResult(
                total_initial_records=0,
                total_emitted_records=0,
                missing_count=0,
                missing_rate_observed=0.0,
                below_lod_count=0,
                below_lod_rate_observed=0.0,
                overrange_count=0,
                overrange_rate_observed=0.0,
                duplicate_count=0,
                duplicate_rate_observed=0.0,
                timestamp_jitter_count=0,
                timestamp_jitter_rate_observed=0.0,
                unit_inconsistent_lot_count=0,
                msa_noise_applied=False,
            )

        working = list(records)

        # 1. MSA Noise
        if apply_msa:
            working = inject_msa_noise(working, rng=self.rng)

        # 2. Censoring (BELOW_LOD on leakage, OVERRANGE on all except Escape Set)
        leakage_count_before = sum(
            1
            for r in working
            if r.parameter in (ParameterName.IDDQ_STANDBY.value, ParameterName.LEAKAGE_INPUT.value)
        )
        working = inject_censoring(
            records=working,
            below_lod_rate=self.below_lod_rate,
            overrange_rate=self.overrange_rate,
            limits=self.limits,
            rng=self.rng,
            escape_component_ids=escape_component_ids,
        )
        below_lod_count = sum(1 for r in working if r.status == MeasurementStatus.BELOW_LOD.value)
        overrange_count = sum(1 for r in working if r.status == MeasurementStatus.OVERRANGE.value)

        # 3. Missing read-points (drop rows)
        working, dropped = inject_missing_rows(
            records=working,
            missing_rate=self.missing_rate,
            rng=self.rng,
        )
        missing_count = len(dropped)

        # 4. Duplicate rows
        working_before_dups = len(working)
        working = inject_duplicates(
            records=working,
            duplicate_rate=self.duplicate_rate,
            rng=self.rng,
        )
        duplicate_count = sum(1 for r in working if r.is_duplicate)

        # 5. Timestamp jitter
        original_timestamps = [r.read_timestamp for r in working]
        working = inject_timestamp_jitter(
            records=working,
            jitter_rate=self.timestamp_jitter_rate,
            rng=self.rng,
        )
        jitter_count = sum(
            1
            for r, orig_ts in zip(working, original_timestamps, strict=True)
            if r.read_timestamp != orig_ts
        )

        # 6. Unit inconsistency
        mismatch_lots = set(unit_mismatch_lots or [])
        if mismatch_lots:
            working = inject_unit_inconsistencies(
                records=working,
                target_lot_ids=mismatch_lots,
            )

        # Ensure Escape Set members strictly satisfy inside-limits constraint (TEST-GEN-004 / DR-04)
        if escape_component_ids:
            escape_set = set(escape_component_ids)
            for r in working:
                if r.component_id in escape_set:
                    lim = self.limits.get(r.parameter)
                    if lim:
                        if lim.absolute_max is not None and r.measurement_value >= lim.absolute_max:
                            r.measurement_value = float(lim.absolute_max - 0.5)
                        if lim.absolute_min is not None and r.measurement_value <= lim.absolute_min:
                            r.measurement_value = float(lim.absolute_min + 0.5)
                        if r.status == MeasurementStatus.OVERRANGE.value:
                            r.status = MeasurementStatus.OK.value

        # Compile audit statistics
        below_lod_rate_obs = (
            (below_lod_count / leakage_count_before) if leakage_count_before > 0 else 0.0
        )
        overrange_rate_obs = overrange_count / initial_count
        missing_rate_obs = missing_count / (initial_count or 1)
        duplicate_rate_obs = duplicate_count / (working_before_dups or 1)
        jitter_rate_obs = jitter_count / (len(working) or 1)

        result = ImperfectionResult(
            total_initial_records=initial_count,
            total_emitted_records=len(working),
            missing_count=missing_count,
            missing_rate_observed=float(missing_rate_obs),
            below_lod_count=below_lod_count,
            below_lod_rate_observed=float(below_lod_rate_obs),
            overrange_count=overrange_count,
            overrange_rate_observed=float(overrange_rate_obs),
            duplicate_count=duplicate_count,
            duplicate_rate_observed=float(duplicate_rate_obs),
            timestamp_jitter_count=jitter_count,
            timestamp_jitter_rate_observed=float(jitter_rate_obs),
            unit_inconsistent_lot_count=len(mismatch_lots),
            msa_noise_applied=apply_msa,
        )

        return working, result

    def apply_to_lot(
        self,
        lot: StratifiedLot,
        unit_mismatch_lots: set[str] | list[str] | None = None,
        apply_msa: bool = True,
        escape_component_ids: set[str] | list[str] | None = None,
    ) -> tuple[list[MeasurementRecord], ImperfectionResult]:
        """Convert a StratifiedLot to records and apply all imperfections."""
        records = convert_lot_to_records(lot, limits=self.limits)
        escapes = escape_component_ids or {p.component_id for p in lot.parts if p.is_escape}
        return self.apply(
            records=records,
            unit_mismatch_lots=unit_mismatch_lots,
            apply_msa=apply_msa,
            escape_component_ids=escapes,
        )
