def convert_part_to_records(
    part: StratumPart,
    limits: dict[str, ParameterLimitConfig] | None = None,
    start_time: datetime | None = None,
    voltage: float = 3.3,
    board_id: str = "BRD-01",
    tester_id: str = "TESTER-01",
    operator_id: str = "OP-01",
    ingest_id: str = "ING-2026-001",
) -> list[MeasurementRecord]:
    """Convert a StratumPart into raw measurement records across all parameters and read-points."""
    p_limits = limits if limits is not None else default_parameter_limits()
    t_start = start_time if start_time is not None else datetime(2026, 9, 1, 8, 0, tzinfo=UTC)

    records: list[MeasurementRecord] = []
    zone_name = getattr(part.trajectory, "thermal_zone_id", None) or (
        part.trajectory.thermal_zone.zone_id
        if hasattr(part.trajectory, "thermal_zone") and part.trajectory.thermal_zone
        else "ZONE-1"
    )
    actual_temps = getattr(part.trajectory, "actual_temperatures_c", {})

    for param, pt_dict in part.values.items():
        limit_cfg = p_limits.get(param)
        unit = limit_cfg.unit if limit_cfg else "uA"
        abs_min = limit_cfg.absolute_min if limit_cfg else None
        abs_max = limit_cfg.absolute_max if limit_cfg else None

        for t, val in sorted(pt_dict.items()):
            actual_temp = actual_temps.get(t, 125.0)
            read_time = t_start + timedelta(hours=t)

            records.append(
                MeasurementRecord(
                    component_id=part.component_id,
                    lot_id=part.lot_id,
                    component_type=part.component_type.value,
                    parameter=param,
                    elapsed_hours=t,
                    measurement_value=float(val),
                    measurement_unit=unit,
                    status=MeasurementStatus.OK.value,
                    temperature_c=float(actual_temp),
                    voltage_v=voltage,
                    read_timestamp=read_time.isoformat(),
                    absolute_limit_low=abs_min,
                    absolute_limit_high=abs_max,
                    board_id=board_id,
                    socket_id=part.socket_id,
                    thermal_zone=zone_name,
                    tester_id=tester_id,
                    operator_id=operator_id,
                    data_provenance="SYNTHETIC",
                    ingest_id=ingest_id,
                )
            )

    return records


def convert_lot_to_records(
    lot: StratifiedLot,
    limits: dict[str, ParameterLimitConfig] | None = None,
    start_time: datetime | None = None,
    operator_pool: list[str] | None = None,
    tester_pool: list[str] | None = None,
) -> list[MeasurementRecord]:
    """Convert an entire StratifiedLot into measurement records."""
    operators = operator_pool or ["OP-01", "OP-02", "OP-03", "OP-04"]
    testers = tester_pool or ["TESTER-01", "TESTER-02"]

    all_records: list[MeasurementRecord] = []
    for i, part in enumerate(lot.parts):
        op = operators[i % len(operators)]
        tester = testers[i % len(testers)]
        part_records = convert_part_to_records(
            part=part,
            limits=limits,
            start_time=start_time,
            operator_id=op,
            tester_id=tester,
        )
        all_records.extend(part_records)

    return all_records


