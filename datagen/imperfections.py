"""Realistic data imperfection injection (Phase 2, T-204).

Implements deliberate real-world imperfections specified in DATASET_SPEC.md § 8:
  1. Missing read-point rows (1.5% default) — exercises FR-103 and INSUFFICIENT_DATA path.
  2. BELOW_LOD censored readings (0.5% of leakage rows) — retained, not coerced to 0 (FR-107).
  3. OVERRANGE readings (0.2% default) — retained as overrange, not coerced to limits (FR-107).
  4. Duplicate (part, param, hours) rows (0.3% default) — tests duplicate detection (FR-103).
  5. Unit inconsistency (mA where uA expected, 2 lots default) — tests unit validation (FR-108).
  6. Timestamp jitter / mild non-monotonicity (1.0% default) — tests ordering robustness (FR-103).
  7. Measurement System Analysis (MSA) noise — Gage R&R repeatability & reproducibility
     (operator/tester/socket) with heteroscedastic scaling (D-I-03, D-CD-04).

Invariants:
  - DR-01: Synthetic dataset generated by seeded, specified generator.
  - DR-03: Every generator parameter carries a provenance tag (TEST-GEN-001).
  - DR-09: data_provenance is always "SYNTHETIC" (TEST-PROV-004).
  - DR-10: Generator cannot import model code (backend/core/**).
  - FR-103: Detect missing read-points, duplicates, timestamp jitter.
  - FR-107: Censored readings (<LOD, OVERRANGE) retained as first-class, never coerced to 0.
  - FR-108: Unit mismatches rejected, never silently rescaled.
"""

from __future__ import annotations

from dataclasses import asdict, dataclass
from datetime import UTC, datetime, timedelta
from typing import TYPE_CHECKING, Any

import numpy as np

from datagen.config.schema import (
    DatagenConfig,
    MeasurementStatus,
    ParameterLimitConfig,
    ParameterName,
    default_parameter_limits,
)

if TYPE_CHECKING:
    from datagen.strata import StratifiedLot, StratumPart

