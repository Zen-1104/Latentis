def inject_missing_rows(
    records: list[MeasurementRecord],
    missing_rate: float = 0.015,
    rng: np.random.Generator | None = None,
) -> tuple[list[MeasurementRecord], list[MeasurementRecord]]:
    """Inject missing read-point rows (DATASET_SPEC § 8).

    Exercises FR-103 and the INSUFFICIENT_DATA path.

    Args:
        records: List of measurement records.
        missing_rate: Fraction of rows to drop (default 0.015 = 1.5%).
        rng: Random generator.

    Returns:
        tuple of (retained_records, dropped_records).
    """
    if not records or missing_rate <= 0.0:
        return list(records), []

    generator = rng if rng is not None else np.random.default_rng()
    n = len(records)
    mask = generator.random(n) >= missing_rate

    retained: list[MeasurementRecord] = []
    dropped: list[MeasurementRecord] = []

    for rec, keep in zip(records, mask, strict=True):
        if keep:
            retained.append(rec)
        else:
            dropped.append(rec)

    return retained, dropped


def inject_censoring(
    records: list[MeasurementRecord],
    below_lod_rate: float = 0.005,
    overrange_rate: float = 0.002,
    limits: dict[str, ParameterLimitConfig] | None = None,
    rng: np.random.Generator | None = None,
    lod_thresholds: dict[str, float] | None = None,
    escape_component_ids: set[str] | list[str] | None = None,
) -> list[MeasurementRecord]:
    """Inject BELOW_LOD and OVERRANGE censored readings (DATASET_SPEC § 8, FR-107).

    Guarantees:
      - BELOW_LOD applies strictly to leakage rows (iddq_standby, leakage_input).
      - Censoring is retained as a first-class value, NEVER coerced to 0 or limit.
      - OVERRANGE reading is flagged with OVERRANGE status and set to instrument
        overrange sentinel/saturation value.
      - Escape Set members (S1, S2) are never assigned OVERRANGE (TEST-GEN-004 / DR-04).

    Args:
        records: List of measurement records.
        below_lod_rate: Fraction of leakage rows censored below LOD (default 0.005 = 0.5%).
        overrange_rate: Fraction of all readings exceeding instrument range (default 0.002 = 0.2%).
        limits: Parameter limit configurations.
        rng: Random generator.
        lod_thresholds: Custom LOD values per parameter.
        escape_component_ids: Component IDs in Escape Set to protect from OVERRANGE.

    Returns:
        Modified records with censoring applied.
    """
    if not records:
        return []

    generator = rng if rng is not None else np.random.default_rng()
    p_limits = limits if limits is not None else default_parameter_limits()
    escape_set = set(escape_component_ids) if escape_component_ids else set()

    # Domain default LOD thresholds per parameter
    default_lods: dict[str, float] = {
        ParameterName.IDDQ_STANDBY.value: 0.10,  # 100 nA instrument floor
        ParameterName.LEAKAGE_INPUT.value: 0.05,  # 50 pA instrument floor
    }
    lods = lod_thresholds or default_lods

    modified: list[MeasurementRecord] = []

    for rec in records:
        # Create shallow copy
        new_rec = MeasurementRecord(**asdict(rec))

        # 1. BELOW_LOD for leakage parameters
        is_leakage = rec.parameter in (
            ParameterName.IDDQ_STANDBY.value,
            ParameterName.LEAKAGE_INPUT.value,
        )
        if is_leakage and below_lod_rate > 0.0 and float(generator.random()) < below_lod_rate:
            lod_val = lods.get(rec.parameter, 0.05)
            # Set status to BELOW_LOD; record the LOD limit value, neither 0.0 nor silent (FR-107)
            new_rec.status = MeasurementStatus.BELOW_LOD.value
            new_rec.measurement_value = float(lod_val)
            modified.append(new_rec)
            continue

        # 2. OVERRANGE for all parameters (Escape Set members are excluded per TEST-GEN-004 / DR-04)
        is_escape_part = rec.component_id in escape_set
        if (
            not is_escape_part
            and overrange_rate > 0.0
            and float(generator.random()) < overrange_rate
        ):
            limit_cfg = p_limits.get(rec.parameter)
            abs_max = limit_cfg.absolute_max if limit_cfg and limit_cfg.absolute_max else 100.0
            # Overrange saturated instrument reading (e.g. 1.25x limit, not coerced to limit)
            new_rec.status = MeasurementStatus.OVERRANGE.value
            new_rec.measurement_value = float(abs_max * float(generator.uniform(1.20, 1.40)))
            modified.append(new_rec)
            continue

        modified.append(new_rec)

    return modified


def inject_duplicates(
    records: list[MeasurementRecord],
    duplicate_rate: float = 0.003,
    rng: np.random.Generator | None = None,
) -> list[MeasurementRecord]:
    """Inject duplicate (component_id, parameter, elapsed_hours) rows (DATASET_SPEC § 8).

    Tests FR-103 duplicate detection.

    Args:
        records: List of measurement records.
        duplicate_rate: Fraction of rows to duplicate (default 0.003 = 0.3%).
        rng: Random generator.

    Returns:
        Records containing injected duplicates inserted directly adjacent or at random positions.
    """
    if not records or duplicate_rate <= 0.0:
        return list(records)

    generator = rng if rng is not None else np.random.default_rng()
    result: list[MeasurementRecord] = []

    for rec in records:
        result.append(rec)
        if float(generator.random()) < duplicate_rate:
            # Duplicate row with identical (part, param, hours)
            dup = MeasurementRecord(**asdict(rec))
            dup.is_duplicate = True
            result.append(dup)

    return result


def inject_timestamp_jitter(
    records: list[MeasurementRecord],
    jitter_rate: float = 0.010,
    rng: np.random.Generator | None = None,
    max_jitter_minutes: float = 45.0,
) -> list[MeasurementRecord]:
    """Inject timestamp jitter and mild non-monotonicity (DATASET_SPEC § 8).

    Tests ordering robustness and FR-103 non-monotonic time detection.

    Args:
        records: List of measurement records.
        jitter_rate: Fraction of rows to perturb (default 0.010 = 1.0%).
        rng: Random generator.
        max_jitter_minutes: Maximum perturbation in minutes.

    Returns:
        Records with perturbed timestamps.
    """
    if not records or jitter_rate <= 0.0:
        return list(records)

    generator = rng if rng is not None else np.random.default_rng()
    result: list[MeasurementRecord] = []

    for rec in records:
        new_rec = MeasurementRecord(**asdict(rec))
        if float(generator.random()) < jitter_rate:
            try:
                ts = datetime.fromisoformat(rec.read_timestamp)
                # Perturb backward or forward by up to max_jitter_minutes
                jitter_min = float(generator.uniform(-max_jitter_minutes, max_jitter_minutes))
                perturbed = ts + timedelta(minutes=jitter_min)
                new_rec.read_timestamp = perturbed.isoformat()
            except (ValueError, TypeError):
                pass
        result.append(new_rec)

    return result


def inject_unit_inconsistencies(
    records: list[MeasurementRecord],
    target_lot_ids: set[str] | list[str],
    target_param: str = ParameterName.IDDQ_STANDBY.value,
    original_unit: str = "uA",
    inconsistent_unit: str = "mA",
) -> list[MeasurementRecord]:
    """Inject unit inconsistency on designated lots (DATASET_SPEC § 8, FR-108).

    Emits mA where uA expected for designated lots.
    Guarantees:
      - Unit validation (FR-108) can detect declared unit disagreement with profile.
      - Never silently rescaled.

    Args:
        records: List of measurement records.
        target_lot_ids: Set of lot IDs where unit is corrupted.
        target_param: Parameter to corrupt (default iddq_standby).
        original_unit: Profile unit (default uA).
        inconsistent_unit: Inconsistent unit (default mA).

    Returns:
        Records with unit inconsistency applied to targeted lots.
    """
    target_set = set(target_lot_ids)
    result: list[MeasurementRecord] = []

    for rec in records:
        new_rec = MeasurementRecord(**asdict(rec))
        if rec.lot_id in target_set and rec.parameter == target_param:
            new_rec.measurement_unit = inconsistent_unit
        result.append(new_rec)

    return result


def inject_msa_noise(
    records: list[MeasurementRecord],
    rng: np.random.Generator | None = None,
    repeatability_rel_scale: float = 0.005,
    operator_offsets: dict[str, float] | None = None,
    tester_drift_per_hour: float = 0.0005,
    hetero_exp: float = 0.50,
) -> list[MeasurementRecord]:
    """Inject Measurement System Analysis (MSA) noise components (D-I-03, D-CD-04).

    Decomposes measurement error into standard Gage R&R components:
      1. Equipment Repeatability: Within-gage random noise on every read.
      2. Operator Reproducibility: Operator-specific probe offset (OP-01 vs OP-02).
      3. Tester Drift: Time-dependent instrument calibration drift across read hours.
      4. Heteroscedasticity: Shot-noise scaling proportional to sqrt(value).

    Args:
        records: List of measurement records.
        rng: Random generator.
        repeatability_rel_scale: Relative standard deviation of gage repeatability.
        operator_offsets: Fixed relative bias per operator ID.
        tester_drift_per_hour: Linear tester drift rate per burn-in hour.
        hetero_exp: Heteroscedasticity exponent (default 0.50).

    Returns:
        Records with MSA noise applied.
    """
    if not records:
        return []

    generator = rng if rng is not None else np.random.default_rng()

    # Operator reproducibility offsets (D-I-03: pseudonymous OP-nn)
    op_bias: dict[str, float] = operator_offsets or {
        "OP-01": 0.0,
        "OP-02": 0.008,
        "OP-03": -0.006,
        "OP-04": 0.004,
    }

    result: list[MeasurementRecord] = []

    for rec in records:
        if rec.status != MeasurementStatus.OK.value:
            # Do not corrupt already censored readings
            result.append(rec)
            continue

        new_rec = MeasurementRecord(**asdict(rec))
        val = rec.measurement_value

        # 1. Gage Repeatability (zero-mean equipment noise)
        scale = repeatability_rel_scale * max(abs(val), 0.1)
        if rec.parameter in (ParameterName.IDDQ_STANDBY.value, ParameterName.LEAKAGE_INPUT.value):
            # Heteroscedastic scaling
            scale *= (max(abs(val), 0.1) / 10.0) ** hetero_exp

        repeatability_noise = float(generator.normal(0.0, scale))

        # 2. Operator Reproducibility
        op_offset = op_bias.get(rec.operator_id, 0.0) * val

        # 3. Tester Drift
        drift = tester_drift_per_hour * rec.elapsed_hours * val

        # Rendered MSA measurement
        noisy_val = val + repeatability_noise + op_offset + drift
        if rec.parameter != ParameterName.VTH_SHIFT.value and noisy_val < 0.0:
            noisy_val = max(0.01, val * 0.1)

        new_rec.measurement_value = float(noisy_val)
        result.append(new_rec)

    return result


