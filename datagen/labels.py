# =============================================================================
# 5. Independent Oracle Function (TEST-GEN-005)
# =============================================================================


def recompute_ground_truth_labels(
    data: list[MeasurementRecord] | list[StratumPart] | StratifiedLot | dict[str, Any],
    limits: dict[str, ParameterLimitConfig] | None = None,
) -> dict[str, PartLabelResult]:
    """Recompute every label from emitted values with an independent function (TEST-GEN-005).

    Oracle Requirement:
      Intent flags must not appear in the derivation. Recomputes FailureLabel,
      Stratum, is_escape, and must_flag strictly from the emitted measurements.

    Args:
        data: List of MeasurementRecord, list of StratumPart, StratifiedLot, or nested values.
        limits: Parameter screening limits.

    Returns:
        Dict mapping component_id to PartLabelResult.
    """
    from datagen.imperfections import MeasurementRecord
    from datagen.strata import StratifiedLot, StratumPart

    p_limits = limits if limits is not None else default_parameter_limits()

    # Case A: StratifiedLot
    if isinstance(data, StratifiedLot):
        return derive_lot_labels(
            parts=data.parts,
            limits=p_limits,
            lot_id=data.lot_id,
            is_lot_shifted=data.is_shifted_lot,
        )

    # Case B: List of MeasurementRecord
    if isinstance(data, list) and data and isinstance(data[0], MeasurementRecord):
        # Group records by (lot_id, component_id, parameter, elapsed_hours)
        parts_by_lot: dict[str, dict[str, dict[str, dict[int, float]]]] = {}
        for r in data:
            lot_dict = parts_by_lot.setdefault(r.lot_id, {})
            comp_dict = lot_dict.setdefault(r.component_id, {})
            pt_dict = comp_dict.setdefault(r.parameter, {})
            pt_dict[r.elapsed_hours] = r.measurement_value

        all_results: dict[str, PartLabelResult] = {}
        for l_id, lot_parts in parts_by_lot.items():
            lot_res = derive_lot_labels(parts=lot_parts, limits=p_limits, lot_id=l_id)
            all_results.update(lot_res)
        return all_results

    # Case C: List of StratumPart
    if isinstance(data, list) and data and isinstance(data[0], StratumPart):
        first_lot_id = data[0].lot_id
        is_shifted = getattr(data[0], "lot_shift_applied", False)
        return derive_lot_labels(
            parts=data,
            limits=p_limits,
            lot_id=first_lot_id,
            is_lot_shifted=is_shifted,
        )

    # Case D: Raw dictionary
    if isinstance(data, dict):
        return derive_lot_labels(parts=data, limits=p_limits)

    return {}
