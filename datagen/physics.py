class FactorCorrelationModel:
    """Factor model generating realistic multi-parameter correlation (DATA_GENERATION_SPEC § 5).

    Latent factors:
        f_supply, f_threshold, f_package ~ Normal(0, 1) per part
        f_leak_specific ~ Normal(0, 1)

    Loadings:
        iddq      += λ₁ · f_supply
        icc       += λ₂ · f_supply
        leakage   += λ₃ · f_supply + λ₄ · f_leak_specific
        prop_delay+= λ₅ · f_threshold
        vth_shift += λ₆ · f_threshold
        output_res+= λ₇ · f_package
    """

    def __init__(
        self,
        lambda_supply_iddq: float = 0.70,
        lambda_supply_icc: float = 0.75,
        lambda_supply_leakage: float = 0.30,
        lambda_leak_specific: float = 0.60,
        lambda_threshold_delay: float = 0.65,
        lambda_threshold_vth: float = 0.60,
        lambda_package_res: float = 0.80,
    ) -> None:
        self.l_iddq = float(lambda_supply_iddq)
        self.l_icc = float(lambda_supply_icc)
        self.l_leak_sup = float(lambda_supply_leakage)
        self.l_leak_spec = float(lambda_leak_specific)
        self.l_delay = float(lambda_threshold_delay)
        self.l_vth = float(lambda_threshold_vth)
        self.l_res = float(lambda_package_res)

        # Compute idiosyncratic variances so Var(z) = 1.0 for each parameter
        self.eps_iddq = math.sqrt(max(0.0, 1.0 - self.l_iddq**2))
        self.eps_icc = math.sqrt(max(0.0, 1.0 - self.l_icc**2))
        self.eps_leak = math.sqrt(max(0.0, 1.0 - (self.l_leak_sup**2 + self.l_leak_spec**2)))
        self.eps_delay = math.sqrt(max(0.0, 1.0 - self.l_delay**2))
        self.eps_vth = math.sqrt(max(0.0, 1.0 - self.l_vth**2))
        self.eps_res = math.sqrt(max(0.0, 1.0 - self.l_res**2))

    def sample_shocks(
        self,
        rng: np.random.Generator,
        is_joint_only: bool = False,
    ) -> tuple[dict[str, float], dict[str, float]]:
        """Sample standardized correlated parameter shocks z(p) ~ N(0, 1).

        Args:
            rng: Seeded NumPy Generator.
            is_joint_only: If True, inject off-manifold factor shock (DATA_GENERATION_SPEC § 5.1).

        Returns:
            Tuple of (standardized_shocks, latent_factors).
        """
        # Sample latent factors
        f_supply = float(rng.normal(0.0, 1.0))
        f_threshold = float(rng.normal(0.0, 1.0))
        f_package = float(rng.normal(0.0, 1.0))
        f_leak_specific = float(rng.normal(0.0, 1.0))

        if is_joint_only:
            # Joint-only anomaly: break supply relationship by perturbing leak-specific factor
            # keeps marginals inside ~2.5 sigma but moves off-manifold
            f_supply = float(rng.uniform(-0.5, 0.5))
            f_leak_specific = 2.4  # off-manifold leakage path

        # Sample independent idiosyncratic standard normals
        e_iddq = float(rng.normal(0.0, 1.0))
        e_icc = float(rng.normal(0.0, 1.0))
        e_leak = float(rng.normal(0.0, 1.0))
        e_delay = float(rng.normal(0.0, 1.0))
        e_vth = float(rng.normal(0.0, 1.0))
        e_res = float(rng.normal(0.0, 1.0))

        # Combine via factor loadings
        z_iddq = self.l_iddq * f_supply + self.eps_iddq * e_iddq
        z_icc = self.l_icc * f_supply + self.eps_icc * e_icc
        z_leak = (
            self.l_leak_sup * f_supply + self.l_leak_spec * f_leak_specific + self.eps_leak * e_leak
        )
        z_delay = self.l_delay * f_threshold + self.eps_delay * e_delay
        z_vth = self.l_vth * f_threshold + self.eps_vth * e_vth
        z_res = self.l_res * f_package + self.eps_res * e_res

        shocks = {
            ParameterName.IDDQ_STANDBY.value: z_iddq,
            ParameterName.ICC_ACTIVE.value: z_icc,
            ParameterName.LEAKAGE_INPUT.value: z_leak,
            ParameterName.PROP_DELAY.value: z_delay,
            ParameterName.VTH_SHIFT.value: z_vth,
            ParameterName.OUTPUT_RES.value: z_res,
        }

        factors = {
            "f_supply": f_supply,
            "f_threshold": f_threshold,
            "f_package": f_package,
            "f_leak_specific": f_leak_specific,
        }

        return shocks, factors


