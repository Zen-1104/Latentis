class ArrheniusModel:
    """Thermal acceleration model based on the Arrhenius reaction rate equation (D-B-01).

    Formula:
        AF = exp( (Ea / k_B) * (1 / T_ref_k - 1 / T_stress_k) )
    """

    def __init__(self, k_boltzmann_ev_per_k: float, t_ref_c: float) -> None:
        """Initialize Arrhenius acceleration calculator.

        Args:
            k_boltzmann_ev_per_k: Boltzmann constant in eV/K (typically 8.617333262e-5).
            t_ref_c: Reference burn-in temperature in Celsius (typically 125.0 °C).
        """
        if k_boltzmann_ev_per_k <= 0:
            raise ValueError(f"Boltzmann constant must be positive, got {k_boltzmann_ev_per_k}")
        if t_ref_c <= -CELSIUS_TO_KELVIN:
            raise ValueError(f"Reference temperature must be above absolute zero, got {t_ref_c} °C")

        self.k_b = float(k_boltzmann_ev_per_k)
        self.t_ref_c = float(t_ref_c)
        self.t_ref_k = self.t_ref_c + CELSIUS_TO_KELVIN

    def compute_af(self, temp_c: float | np.ndarray, ea_ev: float) -> float | np.ndarray:
        """Compute the Arrhenius Acceleration Factor (AF) relative to reference temperature.

        When temp_c == t_ref_c, AF == 1.0.
        When temp_c > t_ref_c, AF > 1.0 (accelerated degradation).
        When temp_c < t_ref_c, AF < 1.0 (decelerated degradation).

        Args:
            temp_c: Operating or zone temperature in Celsius.
            ea_ev: Activation energy in electron-volts (eV).

        Returns:
            Acceleration factor (dimensionless ratio).
        """
        if ea_ev <= 0:
            raise ValueError(f"Activation energy must be positive, got {ea_ev} eV")

        if isinstance(temp_c, (int, float)):
            if temp_c <= -CELSIUS_TO_KELVIN:
                raise ValueError(
                    f"Temperature must be above absolute zero (-273.15 °C), got {temp_c}"
                )
            t_k = float(temp_c) + CELSIUS_TO_KELVIN
            exponent = (ea_ev / self.k_b) * (1.0 / self.t_ref_k - 1.0 / t_k)
            return float(math.exp(exponent))

        arr = np.asarray(temp_c, dtype=np.float64)
        if np.any(arr <= -CELSIUS_TO_KELVIN):
            raise ValueError("All temperatures must be above absolute zero (-273.15 °C)")
        t_k_arr = arr + CELSIUS_TO_KELVIN
        exp_arr = (ea_ev / self.k_b) * (1.0 / self.t_ref_k - 1.0 / t_k_arr)
        result_arr: np.ndarray = np.exp(exp_arr)
        return result_arr

    def equivalent_field_hours(
        self,
        burn_in_hours: float,
        stress_temp_c: float,
        field_temp_c: float,
        ea_ev: float,
    ) -> float:
        """Convert burn-in stress hours into equivalent operational mission hours (FR-309, D-B-01).

        Formula:
            AF_field = exp( (Ea / k_B) * (1 / T_field_K - 1 / T_stress_K) )
            equiv_hours = burn_in_hours * AF_field
        """
        if burn_in_hours < 0:
            raise ValueError(f"Burn-in hours cannot be negative, got {burn_in_hours}")
        if ea_ev <= 0:
            raise ValueError(f"Activation energy must be positive, got {ea_ev}")
        if stress_temp_c <= -CELSIUS_TO_KELVIN or field_temp_c <= -CELSIUS_TO_KELVIN:
            raise ValueError("Temperatures must be above absolute zero")

        t_stress_k = stress_temp_c + CELSIUS_TO_KELVIN
        t_field_k = field_temp_c + CELSIUS_TO_KELVIN
        exponent = (ea_ev / self.k_b) * (1.0 / t_field_k - 1.0 / t_stress_k)
        af_field = math.exp(exponent)
        return float(burn_in_hours * af_field)


