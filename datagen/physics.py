class DegradationShapeModel:
    """Degradation shape model normalized so Phi(0) = 0 and Phi(24) = 1.0."""

    def __init__(
        self,
        family: ShapeFamily = ShapeFamily.POWER_LAW,
        default_exponent: float = 0.50,
        time_constant_tau: float = 24.0,
    ) -> None:
        """Initialize shape function model.

        Args:
            family: ShapeFamily (power_law, log_time, saturating, linear).
            default_exponent: Exponent n for power law (sub-linear when n < 1.0).
            time_constant_tau: Time constant tau in hours for log/saturating forms.
        """
        if default_exponent <= 0:
            raise ValueError(f"Shape exponent must be positive, got {default_exponent}")
        if time_constant_tau <= 0:
            raise ValueError(f"Time constant tau must be positive, got {time_constant_tau}")

        self.family = family
        self.default_exponent = float(default_exponent)
        self.tau = float(time_constant_tau)

    def evaluate(
        self,
        t: float | int | np.ndarray,
        exponent: float | None = None,
    ) -> float | np.ndarray:
        """Evaluate normalized degradation shape function Phi(t).

        Invariants:
            Phi(0) == 0.0
            Phi(24) == 1.0
            Sub-linear: for n < 1.0, Phi(168) < 168/24 = 7.0

        Args:
            t: Elapsed hours (>= 0).
            exponent: Optional per-part exponent n (defaults to self.default_exponent).

        Returns:
            Shape multiplier (dimensionless).
        """
        n = self.default_exponent if exponent is None else float(exponent)
        if n <= 0:
            raise ValueError(f"Shape exponent must be positive, got {n}")

        is_scalar = isinstance(t, (int, float))
        arr = np.asarray([t] if is_scalar else t, dtype=np.float64)

        if np.any(arr < 0):
            raise ValueError("Elapsed time t must be non-negative")

        result = np.zeros_like(arr)
        nonzero_mask = arr > 0

        if not np.any(nonzero_mask):
            return 0.0 if is_scalar else result

        t_nz = arr[nonzero_mask]

        if self.family == ShapeFamily.POWER_LAW:
            result[nonzero_mask] = (t_nz / 24.0) ** n
        elif self.family == ShapeFamily.LOG_TIME:
            denom = math.log(1.0 + 24.0 / self.tau)
            result[nonzero_mask] = np.log(1.0 + t_nz / self.tau) / denom
        elif self.family == ShapeFamily.SATURATING:
            denom = 1.0 - math.exp(-24.0 / self.tau)
            result[nonzero_mask] = (1.0 - np.exp(-t_nz / self.tau)) / denom
        elif self.family == ShapeFamily.LINEAR:
            result[nonzero_mask] = t_nz / 24.0
        else:
            raise ValueError(f"Unsupported shape family {self.family}")

        # Strict boundary enforcement: Phi(0) = 0.0, Phi(24) = 1.0 within float precision
        result[arr == 0.0] = 0.0
        result[np.isclose(arr, 24.0)] = 1.0

        return float(result[0]) if is_scalar else result


