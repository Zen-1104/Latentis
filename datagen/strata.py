@dataclass(frozen=True)
class StratumPart:
    """A generated semiconductor part with full trajectory and stratum context."""

    component_id: str
    lot_id: str
    component_type: ComponentType
    stratum: Stratum
    degradation_class: DegradationClass
    failure_label: FailureLabel
    is_escape: bool
    is_decoy: bool
    values: dict[str, dict[int, float]]  # param -> {t: value}
    trajectory: DegradationTrajectory
    sensor_artefact_magnitude: float = 0.0
    is_joint_only: bool = False
    amplitude_clipped: bool = False
    lot_shift_applied: bool = False
    socket_id: str = "SOCK-01"

    @property
    def value_0h(self) -> dict[str, float]:
        """Values at 0 h read-point."""
        return {p: self.values[p].get(0, 0.0) for p in self.values}

    @property
    def value_24h(self) -> dict[str, float]:
        """Values at 24 h read-point."""
        return {p: self.values[p].get(24, 0.0) for p in self.values}

    @property
    def value_96h(self) -> dict[str, float]:
        """Values at 96 h read-point."""
        return {p: self.values[p].get(96, 0.0) for p in self.values}

    @property
    def value_168h(self) -> dict[str, float]:
        """Values at 168 h read-point."""
        return {p: self.values[p].get(168, 0.0) for p in self.values}


@dataclass(frozen=True)
class StratifiedLot:
    """An entire lot of parts with stratum distributions and process metadata."""

    lot_id: str
    component_type: ComponentType
    parts: list[StratumPart]
    lot_centre: dict[str, float]
    is_shifted_lot: bool = False
    shift_magnitude: float = 0.0

    @property
    def count(self) -> int:
        """Total parts in the lot."""
        return len(self.parts)

    @property
    def stratum_counts(self) -> dict[str, int]:
        """Count of parts per stratum in this lot."""
        counts = {s.value: 0 for s in Stratum}
        for p in self.parts:
            counts[p.stratum.value] += 1
        return counts

    @property
    def escape_count(self) -> int:
        """Count of Escape Set (S1 union S2) parts in this lot."""
        return sum(1 for p in self.parts if p.is_escape)

    @property
    def decoy_count(self) -> int:
        """Count of decoy parts (S3, S4, S5) in this lot."""
        return sum(1 for p in self.parts if p.is_decoy)


