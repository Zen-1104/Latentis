"""Difficulty strata S0-S5 and decoy generation logic (Phase 2, T-203).

Implements the difficulty strata S0-S5, Escape Set (S1 union S2), and benign decoy
behaviour defined in DATASET_SPEC.md § 6, 7 and DATA_GENERATION_SPEC.md § 4, 5.1, 7.1:

  Stratum S0-clear-fail:
    Exceeds an absolute limit at some read-point. Catastrophic failures, large
    step changes (sudden failure), or uncontained drift. Ground truth: FAILED
    or LATENT_DEFECT. Static limit screening catches these.

  Stratum S1-escape-anomaly (Module A flagship target):
    Inside absolute limits at ALL read-points {0, 24, 96, 168} h, but a
    lot-relative outlier at 24 h. Generated from early_latent_defect
    (elevated baseline) or off-manifold joint_only factor anomalies.
    Ground truth: LATENT_DEFECT. is_escape: True.

  Stratum S2-escape-drift (Module B flagship target):
    Inside absolute limits at ALL read-points {0, 24, 96, 168} h, lot-relative
    NORMAL at 24 h, but unsafe projected trajectory / large amplitude drift
    by 168 h. Generated from accelerated_drift with strictly enforced
    inside-limits constraint. Ground truth: LATENT_DEFECT. is_escape: True.

  Stratum S3-decoy-healthy (Decoy: FP pressure):
    Healthy part that sits high in its lot by chance, has elevated measurement
    noise (healthy_noisy 3x), or exhibits normal gradual wear-in drift.
    Ground truth: HEALTHY. Must NOT be flagged as defective / rejected.

  Stratum S4-decoy-sensor (Decoy: attribution target):
    Part is physically healthy, but a measurement/setup artefact corrupts
    the sensor or socket readings (sensor_artefact_magnitude > 0).
    Ground truth: HEALTHY. Must NOT be rejected; must be attributed to
    socket/sensor for retest (RETEST_DIFFERENT_SOCKET per FR-407).

  Stratum S5-lot-shift (Decoy: DPAT vs SPAT test):
    Whole lot mean is shifted coherently (e.g., +2.5 to +3.5 sigma_w), but
    parts are internally consistent and healthy. All parts remain inside
    absolute limits. Ground truth: HEALTHY. DPAT absorbs the shift, so the
    lot passes and parts are not flagged.

Invariants:
  - DR-01: Synthetic dataset generated by seeded, specified generator.
  - DR-03: Every generator parameter carries a provenance tag (TEST-GEN-001).
  - DR-04: Escape Set (S1 union S2) non-empty; ALL members inside ALL limits (TEST-GEN-004).
  - DR-05: Labels derived from rendered values, not intent (TEST-GEN-005, D-014).
  - DR-10: Generator cannot import model code (backend/core/**).
  - D-015: Decoy strata (S3, S4, S5) must NOT be flagged as defective.
"""

