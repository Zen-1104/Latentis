# 1. Stratum Groups and Predicates
# =============================================================================

DECOY_STRATA: frozenset[Stratum] = frozenset(
    {
        Stratum.S3_DECOY_HEALTHY,
        Stratum.S4_DECOY_SENSOR,
        Stratum.S5_LOT_SHIFT,
    }
)

ESCAPE_STRATA: frozenset[Stratum] = frozenset(
    {
        Stratum.S1_ESCAPE_ANOMALY,
        Stratum.S2_ESCAPE_DRIFT,
    }
)

FLAGGED_TARGET_STRATA: frozenset[Stratum] = frozenset(
    {
        Stratum.S0_CLEAR_FAIL,
        Stratum.S1_ESCAPE_ANOMALY,
        Stratum.S2_ESCAPE_DRIFT,
    }
)


def is_decoy(stratum: Stratum | str) -> bool:
    """Return True if stratum is an adversarial decoy that must NOT be flagged (D-015)."""
    s = stratum if isinstance(stratum, Stratum) else Stratum(stratum)
    return s in DECOY_STRATA


def is_escape(stratum: Stratum | str) -> bool:
    """Return True if stratum belongs to the Escape Set S1 union S2 (DATASET_SPEC § 7)."""
    s = stratum if isinstance(stratum, Stratum) else Stratum(stratum)
    return s in ESCAPE_STRATA


def must_flag(stratum: Stratum | str) -> bool:
    """Return True if system is expected to flag this stratum as defective (False for decoys)."""
    s = stratum if isinstance(stratum, Stratum) else Stratum(stratum)
    return s in FLAGGED_TARGET_STRATA


